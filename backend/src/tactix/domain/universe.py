"""Layer 1 entities: the synthetic league, its clubs, players and season history.

All of this is generated by the project and is fully synthetic. No real players, clubs or
competitions are represented.
"""

from __future__ import annotations

from pydantic import BaseModel, Field

from tactix.domain.common import Rating
from tactix.domain.enums import BuildUpStyle, Foot, Position


class PhysicalAttributes(BaseModel):
    pace: Rating = 50
    acceleration: Rating = 50
    stamina: Rating = 50
    strength: Rating = 50
    jumping: Rating = 50


class TechnicalAttributes(BaseModel):
    passing: Rating = 50
    long_passing: Rating = 50
    dribbling: Rating = 50
    first_touch: Rating = 50
    crossing: Rating = 50
    finishing: Rating = 50
    long_shots: Rating = 50
    set_pieces: Rating = 50


class MentalAttributes(BaseModel):
    positioning: Rating = 50
    vision: Rating = 50
    composure: Rating = 50
    decisions: Rating = 50
    aggression: Rating = 50
    work_rate: Rating = 50
    marking: Rating = 50


class GoalkeepingAttributes(BaseModel):
    reflexes: Rating = 50
    handling: Rating = 50
    aerial: Rating = 50
    distribution: Rating = 50
    sweeping: Rating = 50


class PlayerTendencies(BaseModel):
    """The texture the Narrator leans on. Free-text, synthetic, generated from attributes."""

    hot_zones: list[str] = Field(default_factory=list)
    favoured_actions: list[str] = Field(default_factory=list)
    exploitable_weaknesses: list[str] = Field(default_factory=list)


class PlayerState(BaseModel):
    """Mutable within a match / season. Fatigue drives late-game execution drop-off."""

    fatigue: Rating = 0
    morale: Rating = 50
    yellow_cards_season: int = 0
    suspended: bool = False


class Player(BaseModel):
    id: str
    name: str
    number: int = Field(ge=1, le=99)
    positions: list[Position]
    preferred_foot: Foot = Foot.RIGHT
    weak_foot: int = Field(default=3, ge=1, le=5)
    height_cm: int = Field(default=180, ge=150, le=210)
    age: int = Field(default=25, ge=16, le=42)
    physical: PhysicalAttributes = Field(default_factory=PhysicalAttributes)
    technical: TechnicalAttributes = Field(default_factory=TechnicalAttributes)
    mental: MentalAttributes = Field(default_factory=MentalAttributes)
    goalkeeping: GoalkeepingAttributes | None = None
    tendencies: PlayerTendencies = Field(default_factory=PlayerTendencies)
    state: PlayerState = Field(default_factory=PlayerState)


class TacticalIdentity(BaseModel):
    formation: str = "4-3-3"
    build_up: BuildUpStyle = BuildUpStyle.MIXED
    defensive_line_height: Rating = 50
    press_intensity: Rating = 50
    tempo: Rating = 50
    width: Rating = 50
    set_piece_strength: Rating = 50
    philosophy: str = ""


class Club(BaseModel):
    id: str
    name: str
    city: str = ""
    nickname: str = ""
    primary_color: str = "#000000"
    secondary_color: str = "#ffffff"
    tactical_identity: TacticalIdentity = Field(default_factory=TacticalIdentity)
    squad: list[Player] = Field(default_factory=list)
    strengths: list[str] = Field(default_factory=list)
    weaknesses: list[str] = Field(default_factory=list)


class Scorer(BaseModel):
    player_id: str
    club_id: str
    minute: int


class Fixture(BaseModel):
    """A previously played match. More than a scoreline: the material the Historian queries."""

    id: str
    matchday: int
    home_club_id: str
    away_club_id: str
    home_goals: int = 0
    away_goals: int = 0
    scorers: list[Scorer] = Field(default_factory=list)
    home_formation: str = "4-3-3"
    away_formation: str = "4-3-3"
    home_xg: float = 0.0
    away_xg: float = 0.0
    home_possession: float = 50.0
    key_events: list[str] = Field(default_factory=list)
    pattern_note: str = ""  # the recurring story this fixture contributed to


class HeadToHead(BaseModel):
    club_a_id: str
    club_b_id: str
    wins_a: int = 0
    draws: int = 0
    wins_b: int = 0
    last_result: str = ""
    tendencies: list[str] = Field(default_factory=list)


class StandingRow(BaseModel):
    club_id: str
    played: int = 0
    won: int = 0
    drawn: int = 0
    lost: int = 0
    goals_for: int = 0
    goals_against: int = 0
    points: int = 0
    form: list[str] = Field(default_factory=list)  # most recent first, e.g. ["W", "D", "L"]

    @property
    def goal_difference(self) -> int:
        return self.goals_for - self.goals_against


class League(BaseModel):
    id: str
    name: str
    season: str
    clubs: list[Club] = Field(default_factory=list)
    fixtures: list[Fixture] = Field(default_factory=list)
    standings: list[StandingRow] = Field(default_factory=list)
    head_to_head: list[HeadToHead] = Field(default_factory=list)
